// Proposed: src/core/schema/library/catalog.ts and pack.ts
import type {
  Brand, ComponentId, Domain, GeneratorId, HttpsUrl, PackPath, SemVer, SemVerRange,
  Sha256Hex, SimModelId, SpdxExpression,
} from "./component";

/** "official" is reserved and only valid for indexes signed by a compiled-in key. */
export type CatalogId = Brand<string, "CatalogId">;
/** Content-addressed pack id = sha256 of the pack zip. */
export type PackId = Brand<string, "PackId">;
/** Path relative to a mirror base URL, e.g. "v2026.10.1/official.led-5mm-red-1.0.0.stvdpack". */
export type RelUrl = Brand<string, "RelUrl">;
/** RFC 3339 UTC timestamp. */
export type IsoUtc = Brand<string, "IsoUtc">;

// ---------------------------------------------------------------- signed catalog index
// Files at a mirror base URL:
//   index.json          (this interface, UTF-8, <= 16 MiB)
//   index.json.minisig  minisign signature (prehashed Ed25519); trusted comment =
//                       "studiovd-catalog <catalogId> seq=<sequence> expires=<expiresAt>"

export interface CatalogIndex {
  format: "studiovd-catalog";
  schemaVersion: 1;
  catalogId: CatalogId;
  /** Strictly increasing per catalog. Client stores the highest verified value (rollback guard). */
  sequence: number;
  generatedAt: IsoUtc;
  /** Client refuses to INSTALL from an expired index (freeze guard); installed content keeps working. */
  expiresAt: IsoUtc;
  minAppVersion: SemVer;
  /** minisign key id (16 hex chars) that must have produced index.json.minisig. */
  signingKeyId: string;
  /** Base URLs tried in order; integrity never depends on the mirror. */
  mirrors: readonly HttpsUrl[];
  categories: readonly CategoryNode[];
  components: readonly CatalogComponentEntry[];
  packs: Readonly<Record<PackId, PackEntry>>;
  bundles: readonly BundleEntry[];
  /** category path joined by "/" -> preview pack (thumbnails only). */
  previewPacks: Readonly<Record<string, PackId>>;
  generatorPresets: readonly GeneratorPresetEntry[];
  revoked: readonly RevokedEntry[];
  /** Plain-text notices shown in the Library tab (never HTML). */
  notices: readonly { id: string; severity: "info" | "warning"; text: string }[];
}

export interface CategoryNode {
  path: readonly string[];               // ["electrical", "optoelectronics"]
  label: string;
  order: number;
}

export interface CatalogComponentEntry {
  id: ComponentId;
  version: SemVer;
  name: string;
  summary: string;
  category: readonly string[];
  tags: readonly string[];
  family?: string;
  vendor?: string;
  mpn?: string;
  domains: readonly Domain[];            // [] for geometry-only components
  partCount: number;
  triangles: number;
  hasSchematic: boolean;
  license: { geometry: SpdxExpression; data: SpdxExpression };
  requires: {
    app: SemVerRange;
    simModels?: Readonly<Record<SimModelId, number>>;
    generators?: Readonly<Record<GeneratorId, number>>;
  };
  /** SHA-256 of the exact component.json bytes inside the pack: anchors the hash chain. */
  manifestSha256: Sha256Hex;
  /** Smallest pack that contains this component (usually a 1-component pack). */
  pack: PackId;
  /** Thumbnails ship in per-category preview packs (few requests while browsing). */
  thumbnail: { pack: PackId; path: PackPath; sha256: Sha256Hex };
  publishedAt: IsoUtc;
  deprecated?: { reason: string; replacedBy?: ComponentId };
}

export interface PackEntry {
  url: RelUrl;
  sha256: Sha256Hex;                      // equals the PackId
  bytes: number;                          // download is aborted past this many bytes
  uncompressedBytes: number;              // sum of entry sizes; extraction aborts past this
  entries: number;                        // zip entry count
}

export interface BundleEntry {
  id: string;                             // "electrical-all"
  label: string;
  pack: PackId;                           // multi-component pack
  components: readonly { id: ComponentId; version: SemVer }[];
}

/** Virtual components: no download, geometry generated by in-app code. */
export interface GeneratorPresetEntry {
  id: ComponentId;                        // "gen/bearing-608-2rsh"
  version: SemVer;
  name: string;
  category: readonly string[];
  tags: readonly string[];
  generator: GeneratorId;
  generatorMajor: number;
  params: Readonly<Record<string, number | string | boolean>>;
  /** Small manifest overlay (anchors names, mass, license of the dimension data). */
  manifestSha256: Sha256Hex;
  pack: PackId;                           // tiny pack holding component.json + thumbnail only
}

export interface RevokedEntry {
  id: ComponentId;
  version: SemVer;
  reason: string;
  severity: "yanked" | "security";        // "security": also flagged in open projects
}

// ---------------------------------------------------------------- pack (.stvdpack zip)

export interface PackManifest {            // pack.json at the zip root
  format: "studiovd-pack";
  schemaVersion: 1;
  createdBy: string;                       // "studiovd-pack-builder 1.0.0" | "StudioVD 0.14.0"
  createdAt: IsoUtc;
  components: readonly {
    id: ComponentId;
    version: SemVer;
    manifestPath: PackPath;                // "components/official/led-5mm-red/1.0.0/component.json"
    manifestSha256: Sha256Hex;
  }[];
  /** Every other file in the zip, with its hash. Unlisted entries => reject the pack. */
  files: readonly { path: PackPath; sha256: Sha256Hex; bytes: number }[];
  /** Optional embedded copy of the signed index so an offline bundle verifies as official. */
  embeddedIndex?: { indexPath: PackPath; signaturePath: PackPath };
}

// ---------------------------------------------------------------- client-side state (not in packs)

export interface CatalogClientState {     // library/catalogs/<catalogId>/state.json
  catalogId: CatalogId;
  highestSequence: number;
  lastFetchedAt?: IsoUtc;
  lastVerifiedKeyId?: string;
}
